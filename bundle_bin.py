#!/usr/bin/env python3
"""Собирает root-владением защищённую копию бинаря вместе со ВСЕМИ его
non-системными библиотеками (Homebrew-путями), переписывает пути загрузки на
@loader_path и заново подписывает — иначе ядро откажется запускать изменённый
Mach-O.

Зачем: privileged/vpn-run выполняется от root через NOPASSWD sudo. Если он вызывает
бинарь, который лежит в Homebrew (user-владение), любой процесс от пользователя
может подменить этот бинарь ПЕРЕД вызовом — и NOPASSWD отдаёт root через подмену.
Тот же риск для его .dylib-зависимостей, если они не системные (системные — под
SIP, их не подменить).

Требует root для установки в целевой каталог (вызывается из publish.sh, который уже
поднял sudo). Обычный `pip` тут не нужен — только otool/install_name_tool/codesign
из Xcode CLT, они есть в системе.

Плата за это: `brew upgrade <бинарь>` сюда не приезжает — после апгрейда бандл
устарел, надо публиковать заново (`./vpn опубликовать`). Не забывай.
"""
import argparse
import shutil
import subprocess
import sys
from pathlib import Path

# Всё что вне этих префиксов при линковке — считаем "системным", SIP не даст
# подменить, бандлить не нужно.
СИСТЕМНЫЕ_ПРЕФИКСЫ = ("/usr/lib/", "/System/")


def зависимости(бинарь: Path):
    r = subprocess.run(["otool", "-L", str(бинарь)], capture_output=True, text=True, check=True)
    строки = r.stdout.splitlines()[1:]  # первая строка — сам бинарь/дилиб
    итог = []
    for строка in строки:
        путь = строка.strip().split(" ", 1)[0]
        if путь.startswith(СИСТЕМНЫЕ_ПРЕФИКСЫ):
            continue
        итог.append(путь)
    return итог


def id_дилиба(дилиб: Path):
    r = subprocess.run(["otool", "-D", str(дилиб)], capture_output=True, text=True, check=True)
    строки = [s for s in r.stdout.splitlines()[1:] if s.strip()]
    return строки[0].strip() if строки else None


def собрать(исходный_бинарь: Path, каталог_назначения: Path):
    """Копирует бинарь и рекурсивно все non-системные .dylib в каталог_назначения/,
    переписывает все внутренние ссылки на @loader_path/<имя>, подписывает всё
    ad-hoc. Ничего не chown-ит — это забота publish.sh (нужен root)."""
    каталог_назначения.mkdir(parents=True, exist_ok=True)

    имя_бинаря = исходный_бинарь.name
    целевой_бинарь = каталог_назначения / имя_бинаря
    shutil.copy2(исходный_бинарь, целевой_бинарь)
    целевой_бинарь.chmod(0o755)

    обработано = set()
    очередь = [(целевой_бинарь, исходный_бинарь)]
    скопированные_дилибы = []

    while очередь:
        текущий_целевой, текущий_исходный = очередь.pop()
        for зависимость_путь in зависимости(текущий_исходный):
            имя_дилиба = Path(зависимость_путь).name
            if имя_дилиба in обработано:
                continue
            обработано.add(имя_дилиба)

            целевой_дилиб = каталог_назначения / имя_дилиба
            shutil.copy2(зависимость_путь, целевой_дилиб)
            целевой_дилиб.chmod(0o755)
            скопированные_дилибы.append(целевой_дилиб)

            # Переписываем ссылку В бинаре/дилибе, который на него ссылался
            subprocess.run(
                ["install_name_tool", "-change", зависимость_путь,
                 f"@loader_path/{имя_дилиба}", str(текущий_целевой)],
                check=True,
            )
            очередь.append((целевой_дилиб, Path(зависимость_путь)))

    # У каждого скопированного дилиба своё ID — если что-то ещё на него ссылается
    # по абсолютному пути, тоже переписываем на @loader_path.
    for дилиб in скопированные_дилибы:
        старый_id = id_дилиба(дилиб)
        if старый_id:
            subprocess.run(
                ["install_name_tool", "-id", f"@loader_path/{дилиб.name}", str(дилиб)],
                check=True,
            )

    # Подписываем: сначала зависимости, потом сам бинарь (порядок для дерева
    # зависимостей значения не имеет при ad-hoc подписи, но так нагляднее).
    for файл in скопированные_дилибы + [целевой_бинарь]:
        subprocess.run(["codesign", "--force", "--sign", "-", str(файл)], check=True)

    return целевой_бинарь, скопированные_дилибы


def main():
    парсер = argparse.ArgumentParser(description=__doc__)
    парсер.add_argument("бинарь", help="путь к исходному бинарю (например $(which sing-box))")
    парсер.add_argument("каталог", help="куда положить копию + зависимости")
    аргс = парсер.parse_args()

    исходный = Path(аргс.бинарь).resolve()
    if not исходный.is_file():
        print(f"нет такого файла: {исходный}", file=sys.stderr)
        return 1

    целевой_бинарь, дилибы = собрать(исходный, Path(аргс.каталог))
    print(f"бинарь: {целевой_бинарь}")
    print(f"зависимостей забандлено: {len(дилибы)}")
    for д in дилибы:
        print(f"  - {д.name}")

    # Самопроверка — покажет сразу, если переподпись/переписывание путей не удались.
    r = subprocess.run(["codesign", "--verify", "--strict", str(целевой_бинарь)], capture_output=True, text=True)
    if r.returncode != 0:
        print(f"ВНИМАНИЕ: codesign --verify не прошёл: {r.stderr.strip()}", file=sys.stderr)
        return 1
    print("codesign --verify: ок")
    return 0


if __name__ == "__main__":
    sys.exit(main())
